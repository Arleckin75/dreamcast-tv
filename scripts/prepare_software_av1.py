#!/usr/bin/env python3
"""Select a player without rewriting the tracked pubspec or lockfile.

Pass --hardware to remove only the override owned by this script. Other local
overrides are never overwritten. Run flutter pub get after changing players.
"""
from pathlib import Path
import sys

root = Path(__file__).resolve().parent.parent
override = root / 'pubspec_overrides.yaml'
content = '# Generated by scripts/prepare_software_av1.py\n' \
          'dependency_overrides:\n' \
          '  video_player_android:\n' \
          '    path: third_party/video_player_android_noop\n'
if override.exists() and override.read_text(encoding='utf-8') != content:
    raise SystemExit('Unrelated pubspec_overrides.yaml exists; refusing to overwrite it')
if '--hardware' in sys.argv:
    if override.exists():
        override.unlink()
    print('hardware_AV1 uses the standard Android video_player plugin')
    raise SystemExit(0)
override.write_text(content, encoding='utf-8')
print('software_AV1 uses a no-op Android video_player plugin; ExoPlayer is excluded')
