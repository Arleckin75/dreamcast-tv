import 'dart:convert';
import 'dart:io';

/// Run with the pinned Flutter SDK's Dart: dart run scripts/build_tv.dart
/// software|hardware debug|release [--check]. Local overrides and the lockfile
/// are restored even when the build fails.
Future<void> main(List<String> args) async {
  if (args.length < 2 ||
      !['software', 'hardware'].contains(args[0]) ||
      !['debug', 'release'].contains(args[1]) ||
      args.skip(2).any((arg) => arg != '--check')) {
    stderr.writeln(
      'Usage: dart run scripts/build_tv.dart software|hardware debug|release [--check]',
    );
    exitCode = 64;
    return;
  }
  final root = File.fromUri(Platform.script).parent.parent;
  Directory.current = root;
  final sdk = File(
    Platform.resolvedExecutable,
  ).parent.parent.parent.parent.parent;
  final candidate = File.fromUri(
    sdk.uri.resolve(Platform.isWindows ? 'bin/flutter.bat' : 'bin/flutter'),
  );
  final flutter = candidate.existsSync() ? candidate.path : 'flutter';
  final metadata = await Process.run(flutter, [
    '--version',
    '--machine',
  ], runInShell: Platform.isWindows);
  if (metadata.exitCode != 0 ||
      (jsonDecode(metadata.stdout as String) as Map)['frameworkVersion'] !=
          '3.41.5') {
    stderr.writeln('This project requires Flutter 3.41.5.');
    exitCode = 1;
    return;
  }
  final overrides = File('pubspec_overrides.yaml');
  final lock = File('pubspec.lock');
  final originalOverride = overrides.existsSync()
      ? overrides.readAsBytesSync()
      : null;
  final originalLock = lock.existsSync() ? lock.readAsBytesSync() : null;
  const content =
      '# Generated by scripts/prepare_software_av1.py\n'
      'dependency_overrides:\n'
      '  video_player_android:\n'
      '    path: third_party/video_player_android_noop\n';
  if (originalOverride != null && utf8.decode(originalOverride) != content) {
    stderr.writeln(
      'An unrelated pubspec_overrides.yaml exists; refusing to overwrite it.',
    );
    exitCode = 1;
    return;
  }
  Future<int> run(List<String> command) async {
    final process = await Process.start(
      flutter,
      command,
      mode: ProcessStartMode.inheritStdio,
      runInShell: Platform.isWindows,
    );
    return process.exitCode;
  }

  try {
    if (args[0] == 'software') {
      overrides.writeAsStringSync(content);
    } else if (overrides.existsSync()) {
      overrides.deleteSync();
    }
    var result = await run(['pub', 'get']);
    if (result == 0 && args.contains('--check')) {
      result = await run(['analyze']);
    }
    if (result == 0 && args.contains('--check')) result = await run(['test']);
    if (result == 0) {
      result = await run([
        'build',
        'apk',
        '--${args[1]}',
        '--flavor',
        '${args[0]}Av1',
        '--target-platform',
        'android-arm,android-arm64',
      ]);
    }
    exitCode = result;
  } finally {
    if (originalOverride == null) {
      if (overrides.existsSync()) overrides.deleteSync();
    } else {
      overrides.writeAsBytesSync(originalOverride);
    }
    if (originalLock != null) lock.writeAsBytesSync(originalLock);
    final restored = await run(['pub', 'get', '--offline']);
    if (restored != 0) {
      stderr.writeln(
        'Run flutter pub get to restore the original dependency graph.',
      );
      if (exitCode == 0) exitCode = restored;
    }
  }
}
